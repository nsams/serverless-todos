// Worker Previews with their own D1 database (see README):
//
//   node scripts/preview.ts deploy [branch]  creates the Preview's database (if needed), applies the migrations and deploys the Preview (run after `vite build`)
//   node scripts/preview.ts delete [branch]  deletes the Preview and its database
//
// The branch defaults to WORKERS_CI_BRANCH (set by Workers Builds) or the current git branch.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const workerName = "serverless-todos";

function wrangler(args: string[], { capture = false } = {}) {
    console.info(`> wrangler ${args.join(" ")}`);
    // run through npx: uses the project's wrangler (also when called outside of an npm script)
    return execFileSync("npx", ["wrangler", ...args], { encoding: "utf8", stdio: ["inherit", capture ? "pipe" : "inherit", "inherit"] });
}

function currentBranch() {
    return process.env.WORKERS_CI_BRANCH || execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8" }).trim();
}

// Preview names end up in a hostname (<preview-name>-serverless-todos.<subdomain>.workers.dev, max. 63 characters per label) and in the database name
function previewName(branch: string) {
    const name = branch
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");
    const maxLength = 36;
    if (name.length <= maxLength) {
        return name;
    }
    // keep truncated names unique
    const hash = createHash("sha256").update(branch).digest("hex").slice(0, 6);
    return `${name.slice(0, maxLength - hash.length - 1).replace(/-+$/, "")}-${hash}`;
}

function databaseName(preview: string) {
    return `${workerName}-preview-${preview}`;
}

function findDatabase(name: string): { uuid: string; name: string } | undefined {
    const output = wrangler(["d1", "list", "--json"], { capture: true });
    const databases = JSON.parse(output.slice(output.indexOf("["))) as { uuid: string; name: string }[];
    return databases.find((database) => database.name === name);
}

function deploy(branch: string) {
    const preview = previewName(branch);
    const name = databaseName(preview);
    console.info(`Preview "${preview}" (branch ${branch}), database ${name}`);

    let database = findDatabase(name);
    if (!database) {
        wrangler(["d1", "create", name]);
        database = findDatabase(name);
        if (!database) {
            throw new Error(`Database ${name} not found after creating it`);
        }
    }

    // Migrations: a separate config with the Preview's database (the Worker's config has the production database at the top level)
    const migrationsConfig = resolve(".wrangler/preview/migrations.json");
    mkdirSync(dirname(migrationsConfig), { recursive: true });
    writeFileSync(
        migrationsConfig,
        JSON.stringify({
            name: workerName,
            d1_databases: [{ binding: "DB", database_name: name, database_id: database.uuid, migrations_dir: resolve("drizzle") }],
        }),
    );
    wrangler(["d1", "migrations", "apply", "DB", "--remote", "--config", migrationsConfig]);

    // Bind the Preview to its database in the config generated by `vite build` (which wrangler uses via .wrangler/deploy/config.json)
    const deployConfig = resolve(".wrangler/deploy/config.json");
    const workerConfig = resolve(dirname(deployConfig), (JSON.parse(readFileSync(deployConfig, "utf8")) as { configPath: string }).configPath);
    const config = JSON.parse(readFileSync(workerConfig, "utf8")) as { previews?: { d1_databases?: unknown[] } };
    if (!config.previews) {
        throw new Error(`No previews block in ${workerConfig}, run \`vite build\` first`);
    }
    config.previews.d1_databases = [{ binding: "DB", database_name: name, database_id: database.uuid }];
    writeFileSync(workerConfig, JSON.stringify(config));

    wrangler(["preview", "--name", preview]);
}

function deletePreview(branch: string) {
    const preview = previewName(branch);
    const name = databaseName(preview);
    console.info(`Deleting Preview "${preview}" (branch ${branch}) and database ${name}`);
    try {
        wrangler(["preview", "delete", "--name", preview, "--skip-confirmation"]);
    } catch {
        // e.g. never deployed or already deleted
        console.warn(`Couldn't delete Preview "${preview}"`);
    }
    if (findDatabase(name)) {
        wrangler(["d1", "delete", name, "--skip-confirmation"]);
    }
}

const [command, branch = currentBranch()] = process.argv.slice(2);
if (command === "deploy") {
    deploy(branch);
} else if (command === "delete") {
    deletePreview(branch);
} else if (command === "name") {
    console.info(previewName(branch));
} else {
    console.error("Usage: node scripts/preview.ts deploy|delete|name [branch]");
    process.exit(1);
}
