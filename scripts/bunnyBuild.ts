import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// After `vite build` for bunny.net (part of `npm run build:bunny`): turns the server build into the deployed Edge Script.
//
// Edge Scripting limits the script's startup time (500 ms), and parsing the app (~1.8 MB) takes too long there. So the Edge Script
// (dist/bunny/script.js) is a small loader that registers the request handler right away and imports the app with the first request,
// from the Storage Zone (ASSETS_URL), where the deployment uploads it with the static files (dist/client/server/app-<hash>.js). The
// file name has the content hash: a running script keeps loading its own version.
//
// The app module contains no secrets (they are environment variables of the script), like the browser's scripts it's public.

const serverBuild = join("dist", "server", "server.bunny.js");
const appDirectory = join("dist", "client", "server");
const scriptDirectory = join("dist", "bunny");

let app = readFileSync(serverBuild, "utf8");
// The bundler's require() for Node's built-in modules (in CommonJS dependencies) is created with createRequire(import.meta.url), which
// only accepts file URLs; a module imported from a URL has an https URL. Built-in modules don't depend on the path.
app = app.replaceAll("(import.meta.url)", '("file:///app.js")');

const appFile = `app-${createHash("sha256").update(app).digest("hex").slice(0, 16)}.js`;
mkdirSync(appDirectory, { recursive: true });
writeFileSync(join(appDirectory, appFile), app);

const script = `// Generated by scripts/bunnyBuild.ts: the Edge Script, loads the app (src/server.bunny.ts) from the Storage Zone with the first request
const appPath = ${JSON.stringify(`server/${appFile}`)};

function getEnv(name) {
    return globalThis.process?.env?.[name] || globalThis.Deno?.env.get(name) || undefined;
}

let app;

function loadApp() {
    const assetsUrl = getEnv("ASSETS_URL");
    if (!assetsUrl) {
        return Promise.reject(new Error("ASSETS_URL is not set"));
    }
    return import(new URL(appPath, assetsUrl.endsWith("/") ? assetsUrl : \`\${assetsUrl}/\`).href).then((module) => module.default);
}

Bunny.v1.serve(async (request) => {
    app ??= loadApp().catch((error) => {
        // retried with the next request
        app = undefined;
        throw error;
    });
    try {
        return await (await app).fetch(request);
    } catch (error) {
        console.error("Request failed", error);
        return new Response("Internal Server Error", { status: 500, headers: { "cache-control": "no-store" } });
    }
});
`;
mkdirSync(scriptDirectory, { recursive: true });
writeFileSync(join(scriptDirectory, "script.js"), script);

console.info(`Edge Script: ${join(scriptDirectory, "script.js")}, app: ${join(appDirectory, appFile)}`);
