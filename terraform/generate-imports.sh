#!/usr/bin/env bash
# Generates import blocks for the Cloudflare resources that already exist (created by wrangler and in the dashboard), so that
# Terraform takes them over instead of creating them again:
#
#   CLOUDFLARE_API_TOKEN=... ./generate-imports.sh > imports.tf
#   terraform plan   # review: it should only show the differences between the existing configuration and the .tf files
#
# Resources that don't exist yet aren't imported (Terraform creates them). Where several candidates exist, the block is
# written as a comment: uncomment the right one.
set -euo pipefail

account_id="${ACCOUNT_ID:-e45f6c5d92148e7357863b7c79ce5763}"
worker_name="${WORKER_NAME:-serverless-todos}"
d1_database_name="${D1_DATABASE_NAME:-serverless-todos}"
ai_gateway_id="${AI_GATEWAY_ID:-default}"

: "${CLOUDFLARE_API_TOKEN:?CLOUDFLARE_API_TOKEN is not set}"

api() {
    curl -fsS -H "Authorization: Bearer ${CLOUDFLARE_API_TOKEN}" "https://api.cloudflare.com/client/v4/accounts/${account_id}$1"
}

# prints an import block, or the candidates as comments if there isn't exactly one
emit() {
    local to="$1" id_prefix="$2" description="$3" candidates="$4" # candidates: lines "<id>\t<label>"
    local count
    count=$(grep -c . <<<"$candidates" || true)
    echo "# ${description}"
    if [[ "$count" == 1 ]]; then
        printf 'import {\n  to = %s\n  id = "%s%s"\n}\n\n' "$to" "$id_prefix" "$(cut -f1 <<<"$candidates")"
    elif [[ "$count" == 0 ]]; then
        printf '# not found: created by Terraform\n\n'
    else
        echo "# TODO several candidates, uncomment the right one:"
        while IFS=$'\t' read -r id label; do
            printf '# import {\n#   to = %s\n#   id = "%s%s" # %s\n# }\n' "$to" "$id_prefix" "$id" "$label"
        done <<<"$candidates"
        echo
    fi
}

echo "# Generated by generate-imports.sh: imports the existing resources into the Terraform state."
echo "# Can be deleted after the first successful \`terraform apply\`."
echo

emit cloudflare_worker.app "${account_id}/" "Worker" \
    "$(api "/workers/workers?per_page=100" | jq -r --arg name "$worker_name" '.result[] | select(.name == $name) | [.id, .name] | @tsv')"

emit cloudflare_d1_database.app "${account_id}/" "D1 database" \
    "$(api "/d1/database?per_page=100" | jq -r --arg name "$d1_database_name" '.result[] | select(.name == $name) | [.uuid, .name] | @tsv')"

emit cloudflare_ai_gateway.app "${account_id}/" "AI Gateway" \
    "$(api "/ai-gateway/gateways?per_page=100" | jq -r --arg id "$ai_gateway_id" '.result[] | select(.id == $id) | [.id, .id] | @tsv')"

emit cloudflare_zero_trust_access_identity_provider.entra_id "accounts/${account_id}/" "Access identity provider (Entra ID)" \
    "$(api "/access/identity_providers" | jq -r '.result[] | select(.type == "azureAD") | [.id, .name] | @tsv')"

worker_id=$(api "/workers/workers?per_page=100" | jq -r --arg name "$worker_name" '.result[] | select(.name == $name) | .id')

# applications that protect the Worker: by Worker destination or by its workers.dev hostname
apps=$(api "/access/apps?per_page=100")
emit cloudflare_zero_trust_access_application.app "accounts/${account_id}/" "Access application" \
    "$(jq -r --arg worker_id "$worker_id" --arg host "${worker_name}." '.result[]
        | select(any(.destinations[]?; .worker_id == $worker_id or ((.uri // "") | startswith($host))) or ((.domain // "") | startswith($host)))
        | [.id, "\(.name) (aud \(.aud))"] | @tsv' <<<"$apps")"

# the reusable policies of these applications
emit cloudflare_zero_trust_access_policy.app "${account_id}/" "Access policy" \
    "$(api "/access/policies?per_page=100" | jq -r --arg name "$worker_name" '.result[]
        | select(.reusable == true and (.name | startswith($name)))
        | [.id, .name] | @tsv')"
